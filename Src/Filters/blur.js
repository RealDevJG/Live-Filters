function blurFilter(_kernel)
{
    return function(_img)
    {
        perPixel(_img, (index, x, y) => 
        {
            const colour = convolute(_img, x, y, _kernel);

            _img.pixels[index + 0] = colour.r;
            _img.pixels[index + 1] = colour.g;
            _img.pixels[index + 2] = colour.b;
        });
    };
}
